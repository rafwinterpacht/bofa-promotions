/**
 * carousel — full-bleed image carousel with arrows and line dots (source .content-carousel).
 * Next/previous and dots slide the track (transform 500ms); the active dot fills (200ms).
 * One presentational clone sits at each end of the track (aria-hidden), like the source.
 *
 * Authoring: one row per slide; the cell holds one or two images. Two = desktop first
 * (from 640px), mobile second; one = used at every width. Alt text is the slide's message.
 *
 * @ew-exempt generated controls — the visually hidden "Change to accessible version" skip
 *   button and the dot numbers are chrome generated by the block, not authored content.
 */

const ICON_NEXT = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 30 55" aria-hidden="true">'
  + '<polyline points="2.1 0.8 0 3 25.8 27.8 0 52.7 2.1 54.8 30 27.8 2.1 0.8" '
  + 'fill-rule="evenodd"></polyline></svg>';
const ICON_PREV = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 30 55" aria-hidden="true">'
  + '<polyline points="27.9 54.8 30 52.7 4.2 27.9 30 3 27.9 0.8 0 27.9 27.9 54.8" '
  + 'fill-rule="evenodd"></polyline></svg>';

let carouselId = 0;

function el(tag, className, attrs = {}) {
  const n = document.createElement(tag);
  if (className) n.className = className;
  Object.entries(attrs).forEach(([k, v]) => n.setAttribute(k, v));
  return n;
}

function stripInstrumentation(node) {
  node.querySelectorAll('[data-prose-index], [data-image-index]').forEach((n) => {
    n.removeAttribute('data-prose-index');
    n.removeAttribute('data-image-index');
  });
  node.removeAttribute('data-prose-index');
  return node;
}

export default function decorate(block) {
  if (block.querySelector(':scope > .carousel-viewport')) return;
  carouselId += 1;
  const uid = `carousel-${carouselId}`;

  // 1. QUERY — one slide per row that holds an image
  const rows = [...block.children].filter((r) => r.querySelector('picture, img'));

  // 2. CREATE
  const skip = el('button', 'carousel-skip', { type: 'button' });
  skip.textContent = 'Change to accessible version';
  const viewport = el('div', 'carousel-viewport');
  const track = el('div', 'carousel-track');
  viewport.append(track);

  // 3. MOVE
  const slides = rows.map((row, i) => {
    const slide = el('div', 'carousel-slide', { id: `${uid}-slide-${i + 1}` });
    const pics = [];
    row.querySelectorAll('picture, img').forEach((p) => {
      if (p.tagName === 'IMG' && p.closest('picture')) return;
      pics.push(p);
    });
    pics.forEach((p, j) => {
      let cls = 'carousel-media';
      if (pics.length > 1) cls += j === 0 ? ' carousel-desktop' : ' carousel-mobile';
      const w = el('div', cls);
      w.append(p);
      slide.append(w);
    });
    slide.querySelectorAll('img').forEach((img) => { img.loading = 'eager'; });
    track.append(slide);
    return slide;
  });

  const next = el('button', 'carousel-arrow carousel-next', { type: 'button', 'aria-label': 'Next' });
  next.innerHTML = ICON_NEXT;
  const prev = el('button', 'carousel-arrow carousel-prev', {
    type: 'button', 'aria-label': 'Previous',
  });
  prev.innerHTML = ICON_PREV;
  const dots = el('ul', 'carousel-dots', { role: 'tablist' });
  const dotItems = slides.map((s, i) => {
    const li = el('li');
    const b = el('button', '', {
      type: 'button',
      role: 'tab',
      'aria-controls': s.id,
      'aria-label': `${i + 1} of ${slides.length}`,
      'aria-selected': 'false',
    });
    b.textContent = String(i + 1);
    li.append(b);
    dots.append(li);
    return li;
  });

  // presentational clones at both ends (source parity: one each side)
  if (slides.length > 1) {
    const clone = (s) => {
      const c = stripInstrumentation(s.cloneNode(true));
      c.removeAttribute('id');
      c.classList.add('is-clone');
      c.setAttribute('aria-hidden', 'true');
      return c;
    };
    track.prepend(clone(slides[slides.length - 1]));
    track.append(clone(slides[0]));
  } else {
    track.style.setProperty('--slide', '0');
  }

  let current = 0;
  const go = (i) => {
    current = (i + slides.length) % slides.length;
    if (slides.length > 1) track.style.setProperty('--slide', String(current + 1));
    slides.forEach((s, j) => s.classList.toggle('is-active', j === current));
    dotItems.forEach((d, j) => {
      d.classList.toggle('is-active', j === current);
      d.firstElementChild.setAttribute('aria-selected', String(j === current));
    });
  };
  next.addEventListener('click', () => go(current + 1));
  prev.addEventListener('click', () => go(current - 1));
  dotItems.forEach((d, i) => d.firstElementChild.addEventListener('click', () => go(i)));
  skip.addEventListener('click', () => block.classList.toggle('accessible'));

  block.setAttribute('aria-roledescription', 'carousel');
  const controls = slides.length > 1 ? [next, prev, dots] : [];
  block.replaceChildren(skip, viewport, ...controls);
  go(0);
}
